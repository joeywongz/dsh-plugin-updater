/**
 * Build the two shipped artifacts:
 *  - dist/client.js: the Vite CommonJS bundle wrapped in the DSH module loader
 *    factory, so `require('react')` resolves through the host page.
 *  - lib/index.js: the Host half compiled by TypeScript.
 */

import { execFileSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bin = (name) => resolve(root, 'node_modules', '.bin', name)

function run(command, args, label) {
  process.stdout.write(`\n[build] ${label}\n`)
  execFileSync(command, args, { cwd: root, stdio: 'inherit' })
}

run(bin('vite'), ['build', '--logLevel', 'warn'], 'vite (client bundle)')

const cjsPath = resolve(root, 'dist', 'client.cjs')
const outPath = resolve(root, 'dist', 'client.js')
const cjs = readFileSync(cjsPath, 'utf8')
const wrapped = `/* dsh-my-plugin-updater — generated by scripts/build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-my-plugin-updater',
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
    try {
${cjs
  .split('\n')
  .map((line) => '      ' + line)
  .join('\n')}
    } catch (error) {
      console.error('[dsh-my-plugin-updater] client bundle failed', error)
      throw error
    }
    return Object.prototype.hasOwnProperty.call(module.exports, 'default') ? module.exports.default : module.exports
  },
})
`
writeFileSync(outPath, wrapped)
rmSync(cjsPath)
process.stdout.write(`[build] wrapped dist/client.js (${wrapped.length} bytes)\n`)

mkdirSync(resolve(root, 'lib'), { recursive: true })
run(bin('tsc'), ['-p', 'tsconfig.host.json'], 'tsc (host half)')
process.stdout.write('\n[build] done\n')
